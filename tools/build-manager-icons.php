<?php
/**
 * Build the manager's CSS icons from the same locked SVGs used by Blade Icons.
 * Run after `composer install` in core/: php tools/build-manager-icons.php
 * The generated CSS is committed so source installs and the installer need no fonts or JS.
 */
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$root = dirname(__DIR__);
$output = $root . '/manager/media/style/common/icons';
$source = $argv[1] ?? $root . '/core/vendor/secondnetwork/blade-tabler-icons/resources/svg';
$icons = json_decode(file_get_contents($output . '/icons.json'), true, 512, JSON_THROW_ON_ERROR);
sort($icons);
$css = "/* Generated by tools/build-manager-icons.php from secondnetwork/blade-tabler-icons. MIT; see LICENSE. */\n";
$css .= ":root{\n";
foreach ($icons as $icon) {
    $file = $source . '/' . $icon . '.svg';
    if (!is_file($file)) {
        throw new RuntimeException('Missing Tabler SVG: ' . $icon);
    }
    $svg = preg_replace('/\s+/', ' ', trim(file_get_contents($file)));
    // A CSS mask uses alpha only, retaining the strokes and fills of the Blade SVG.
    $css .= '--evo-icon-' . $icon . ':url("data:image/svg+xml,' . rawurlencode($svg) . '");' . "\n";
}
$css .= "}\n";
$css .= <<<'CSS'
.evo-icon{display:inline-block;flex-shrink:0;font-style:normal;font-variant:normal;line-height:1;vertical-align:-.125em;text-rendering:auto}
.evo-icon::before{content:"";display:inline-block;width:1em;height:1em;vertical-align:middle;background-color:currentColor;-webkit-mask:var(--evo-icon) center/contain no-repeat;mask:var(--evo-icon) center/contain no-repeat}
.evo-icon-fw{width:1.25em;text-align:center}
.evo-icon-xs{font-size:.75em}.evo-icon-sm{font-size:.875em}.evo-icon-lg{font-size:1.333333em}
.evo-icon-spin{animation:evo-icon-spin 2s linear infinite}.evo-icon-pulse{animation:evo-icon-spin 1s steps(8) infinite}
.evo-icon-spin-hover:hover{animation:evo-icon-spin 2s linear infinite}
.evo-icon-inverse{color:#fff}
.evo-icon-border{border:solid .08em #eee;border-radius:.1em;padding:.2em .25em .15em}
.evo-icon-pull-left{float:left;margin-right:.3em}.evo-icon-pull-right{float:right;margin-left:.3em}
.evo-icon-ul{list-style:none;margin-left:2.5em;padding-left:0}.evo-icon-ul>li{position:relative}
.evo-icon-li{left:-2em;position:absolute;text-align:center;width:2em;line-height:inherit}
.evo-icon-stack{display:inline-block;height:2em;line-height:2em;position:relative;vertical-align:middle;width:2.5em}
.evo-icon-stack-1x,.evo-icon-stack-2x{left:0;position:absolute;text-align:center;width:100%}
.evo-icon-stack-1x{line-height:inherit}.evo-icon-stack-2x{font-size:2em}
.evo-icon-rotate-90{transform:rotate(90deg)}.evo-icon-rotate-180{transform:rotate(180deg)}.evo-icon-rotate-270{transform:rotate(270deg)}
.evo-icon-flip-horizontal{transform:scaleX(-1)}.evo-icon-flip-vertical{transform:scaleY(-1)}.evo-icon-flip-both{transform:scale(-1)}
@keyframes evo-icon-spin{to{transform:rotate(360deg)}}
@media(prefers-reduced-motion:reduce){.evo-icon-spin,.evo-icon-pulse{animation:none}}
CSS;
for ($size = 1; $size <= 10; $size++) {
    $css .= "\n.evo-icon-{$size}x{font-size:{$size}em}";
}
foreach ($icons as $icon) {
    $css .= "\n.evo-icon-{$icon}{--evo-icon:var(--evo-icon-{$icon})}";
}
file_put_contents($output . '/manager-icons.css', $css . "\n");
echo 'Built ' . count($icons) . " Tabler SVG masks.\n";
